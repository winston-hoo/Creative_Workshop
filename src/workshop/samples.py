def build_synthetic_novel() -> str:
    """构造一份合成小说文件，用来验证录入与切分。

    刻意埋了六种真实世界里会遇到的情况：

      1. 文首有目录页（连续标题、中间没有正文）        → 应被排除
      2. 第 4 章标题格式异常（写作「章四 断刀」）      → 应由宽松模板修复
      3. 末尾出现重复的「第六章」                     → 应被识别为重号
      4. 正文里有一句引用了章节标题的对话             → 应被排除，不当成标题
      5. 一行页眉反复出现 6 次                        → 应被报告（默认不删）
      6. 多余空行与行尾空格、破折号、「不是X是Y」      → 应被清洗记录，但标点不动
    """
    lines: list[str] = []

    # ① 目录页（5 行，中间没有正文）
    lines += ["目录"]
    for no, title in [
        ("第一章", "夜行"),
        ("第二章", "旧约"),
        ("第三章", "风起"),
        ("第四章", "断刀"),
        ("第五章", "关外"),
    ]:
        lines.append(f"{no} {title}")
    lines.append("")

    lines.append("卷一 关山")
    lines.append("")

    def chapter(title_line: str, body: list[str]) -> None:
        lines.append(title_line)
        lines.extend(body)
        lines.append("")

    header = "关山灯·内部稿"

    chapter(
        "第一章 夜行",
        [
            header,
            "夜风从关外卷过来，带着沙。",
            "我按住腰间的断刀，朝铁门关的方向看了一眼。关上没有灯，只有风声。",
            "「你还是要走？」沈青棠站在门里，声音很轻。",
            "",
            "",
            "",
            "「我得去。」我说，「三天之内回来。」",
            "她没有再说话，只是把一件旧披风塞进我怀里——那是她父亲留下的东西。   ",
        ],
    )

    chapter(
        "第二章 旧约",
        [
            header,
            "城楼上的旗子换了新的，颜色比去年深一些。",
            "我把披风铺在膝上，数了数上面的补丁。七个。",
            "「你还记得第一章 夜行吗。」她忽然问。",  # ④ 正文引用，带引号
            "我说记得。其实我记得的不止那一晚。",
        ],
    )

    chapter(
        "第三章 风起",
        [
            header,
            "风从北面来的时候，沙子会打在脸上，生疼。",
            "我数着更鼓，一直数到五更。",
            "守关的人换了三班，没人跟我说话。",
        ],
    )

    # ② 第 4 章标题格式异常：严格模板匹配不到，需要宽松模板修复
    chapter(
        "章四 断刀",
        [
            header,
            "刀是断的，断口很旧。",
            "我用拇指压了压那个缺口，像压着一道旧伤。",
            "我不是怕死，我是怕她等不到。",
        ],
    )

    chapter(
        "第五章 关外",
        [
            header,
            "出关的路只有一条，两边都是荒的。",
            "我走了很久，回头看时，铁门关已经小成一线。",
        ],
    )

    chapter(
        "第六章 归来",
        [
            "回来那天下了雨，城门开着。",
            "沈青棠站在门里，还是那件旧披风的颜色。",
        ],
    )

    # ③ 重复的第六章。**必须保留**并加字母后缀，不能丢弃
    #   （真实作品里两章同号、内容不同的情况很常见，丢了就是静默吞内容）
    lines.append("第六章 归来")
    lines.append("她问我这三天去了哪里。我说去了关外。")
    lines.append("她没有再问。")
    lines.append("")

    # ④ 分段重启：番外篇重新从第一章开始编号
    lines.append("未曾设想的道路(番外篇)")
    lines.append("")
    lines.append("第一章 红旗蛮眼熟(番外)")
    lines.append("他从一阵昏昏沉沉里醒过来，先闻到的是铁锈味。")
    lines.append("这个世界的风向和他记得的不一样。")
    lines.append("")

    # ⑤ 格式变体：番外章节不用「第N章」，严格模板命中不到
    lines.append("番外进击的东北空军上")
    lines.append("飞机从云层里钻出来的时候，地面上的雪还没有化。")
    lines.append("")

    return "\n".join(lines)

